const getFunctionSignature = (
  simplifiedFunction: SimplifiedFunction
): string => {
  const parameters = simplifiedFunction.parameters
    .map(parameter =>
      // The implicit `Object`/`Behavior` parameters are always named after
      // what they are: their type would add nothing.
      parameter.isImplicit
        ? parameter.name
        : `${parameter.name}: ${parameter.type}`
    )
    .join(', ');
  return `${simplifiedFunction.functionType} ${
    simplifiedFunction.functionName
  }(${parameters})${simplifiedFunction.isPrivate ? ' [private]' : ''}`;
};

const getCustomObjectSignature = (
  eventsBasedObject: gdEventsBasedObject
): string => {
  const childObjectNames = getChildObjectNames(eventsBasedObject.getObjects());
  const variantNames = getNamedVariantNames(eventsBasedObject);
  return [
    `${childObjectNames.length} child objects${
      childObjectNames.length > 0 ? ` (${childObjectNames.join(', ')})` : ''
    }`,
    `${eventsBasedObject
      .getEventsFunctions()
      .getEventsFunctionsCount()} functions`,
    `${eventsBasedObject.getPropertyDescriptors().getCount()} properties`,
    `variants: ${listNames(variantNames)}`,
  ].join(', ');
};

const getCustomBehaviorSignature = (
  eventsBasedBehavior: gdEventsBasedBehavior
): string =>
  `for ${eventsBasedBehavior.getObjectType() ||
    'any object'} - ${eventsBasedBehavior
    .getPropertyDescriptors()
    .getCount()} properties, ${eventsBasedBehavior
    .getEventsFunctions()
    .getEventsFunctionsCount()} functions`;

