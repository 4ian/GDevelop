const getInspectedExtension = (
  eventsFunctionsExtension: gdEventsFunctionsExtension
): InspectedExtension => {
  const extensionName = eventsFunctionsExtension.getName();
  const isReadOnly = isExtensionFromStore(eventsFunctionsExtension);

  const eventsBasedObjects = eventsFunctionsExtension.getEventsBasedObjects();
  const eventsBasedBehaviors = eventsFunctionsExtension.getEventsBasedBehaviors();
  const freeFunctions = eventsFunctionsExtension.getEventsFunctions();

  const inspectedExtension: InspectedExtension = {
    extensionName,
    fullName: eventsFunctionsExtension.getFullName(),
    shortDescription: eventsFunctionsExtension.getShortDescription(),
    isReadOnly,
    globalVariables: getSimplifiedVariablesContainer(
      gd,
      eventsFunctionsExtension.getGlobalVariables()
    ),
    sceneVariables: getSimplifiedVariablesContainer(
      gd,
      eventsFunctionsExtension.getSceneVariables()
    ),
    dependencies: getSimplifiedDependencies(eventsFunctionsExtension),
    tests: getSimplifiedTests(eventsFunctionsExtension.getTests()),
    customObjects: mapFor(0, eventsBasedObjects.getCount(), i => {
      const eventsBasedObject = eventsBasedObjects.getAt(i);
      const objectName = eventsBasedObject.getName();
      const summary: InspectedCustomObjectSummary = {
        objectName,
        objectType: `${extensionName}::${objectName}`,
        signature: getCustomObjectSignature(eventsBasedObject),
      };
      if (eventsBasedObject.getFullName())
        summary.fullName = eventsBasedObject.getFullName();
      if (eventsBasedObject.isPrivate()) summary.isPrivate = true;
      return summary;
    }),
    customBehaviors: mapFor(0, eventsBasedBehaviors.getCount(), i => {
      const eventsBasedBehavior = eventsBasedBehaviors.getAt(i);
      const behaviorName = eventsBasedBehavior.getName();
      const summary: InspectedCustomBehaviorSummary = {
        behaviorName,
        behaviorType: `${extensionName}::${behaviorName}`,
        signature: getCustomBehaviorSignature(eventsBasedBehavior),
      };
      if (eventsBasedBehavior.getFullName())
        summary.fullName = eventsBasedBehavior.getFullName();
      if (eventsBasedBehavior.getObjectType())
        summary.objectType = eventsBasedBehavior.getObjectType();
      if (eventsBasedBehavior.isPrivate()) summary.isPrivate = true;
      return summary;
    }),
    freeFunctions: mapFor(0, freeFunctions.getEventsFunctionsCount(), i => {
      const simplifiedFunction = getSimplifiedFunction(
        gd,
        freeFunctions.getEventsFunctionAt(i),
        'extension'
      );
      const summary: InspectedFreeFunctionSummary = {
        functionName: simplifiedFunction.functionName,
        functionType: simplifiedFunction.functionType,
        signature: getFunctionSignature(simplifiedFunction),
      };
      if (simplifiedFunction.isPrivate) summary.isPrivate = true;
      if (simplifiedFunction.isLifecycle) summary.isLifecycle = true;
      return summary;
    }),
  };

  if (isReadOnly) {
    inspectedExtension.readOnlyReason = `"${extensionName}" comes from the GDevelop extension store and is updated from there: it is read-only.`;
  }
  if (eventsFunctionsExtension.getDescription())
    inspectedExtension.description = eventsFunctionsExtension.getDescription();
  if (eventsFunctionsExtension.getCategory())
    inspectedExtension.category = eventsFunctionsExtension.getCategory();
  const tags = eventsFunctionsExtension.getTags().toJSArray();
  if (tags.length > 0) inspectedExtension.tags = tags.join(', ');
  if (eventsFunctionsExtension.getVersion())
    inspectedExtension.version = eventsFunctionsExtension.getVersion();
  if (eventsFunctionsExtension.getAuthor())
    inspectedExtension.author = eventsFunctionsExtension.getAuthor();
  if (eventsFunctionsExtension.getOriginIdentifier())
    inspectedExtension.originIdentifier = eventsFunctionsExtension.getOriginIdentifier();

  return inspectedExtension;
};

const getInspectedVariant = (
  project: gdProject,
  eventsBasedObject: gdEventsBasedObject,
  variant: gdEventsBasedObjectVariant,
  PixiResourcesLoader: any
): InspectedVariant => {
  const objects = variant.getObjects();
  const layers = variant.getLayers();

  const objectSizeInfoByName: { [string]: ObjectSizeInfo | null } = {};
  const childObjects = mapFor(0, objects.getObjectsCount(), i => {
    const object = objects.getObjectAt(i);
    const objectName = object.getName();
    objectSizeInfoByName[objectName] = getObjectSizeInfo(
      object,
      project,
      PixiResourcesLoader
    );
    return {
      objectName,
      objectType: object.getType(),
      behaviors: object
        .getAllBehaviorNames()
        .toJSArray()
        .map(behaviorName => ({
          behaviorName,
          behaviorType: object.getBehavior(behaviorName).getTypeName(),
        })),
      objectVariables: getSimplifiedVariablesContainer(
        gd,
        object.getVariables()
      ),
      configuration: formatPropertiesList(
        object.getConfiguration().getProperties()
      ),
    };
  });

  const instances = [];
  for (let i = 0; i < layers.getLayersCount(); i++) {
    const layerName = layers.getLayerAt(i).getName();
    getInstancesInLayoutForLayer(
      variant.getInitialInstances(),
      layerName
    ).forEach(instance => {
      instances.push(
        getSimplifiedInstance(
          instance,
          objectSizeInfoByName[instance.getObjectName()] || null
        )
      );
    });
  }

  // Object groups belong to the events-based object: they are the same for
  // every variant.
  const objectGroups = eventsBasedObject.getObjects().getObjectGroups();

  const inspectedVariant: InspectedVariant = {
    variantName: variant.getName(),
    isDefaultVariant: variant.getName() === '',
    area: getSimplifiedArea(variant),
    layers: mapFor(0, layers.getLayersCount(), i => {
      const layer = layers.getLayerAt(i);
      const effects = layer.getEffects();
      const inspectedLayer: InspectedLayer = {
        layerName: layer.getName(),
        position: i,
        visible: layer.getVisibility(),
        effects: mapFor(0, effects.getEffectsCount(), effectIndex => {
          const effect = effects.getEffectAt(effectIndex);
          return {
            effectName: effect.getName(),
            effectType: effect.getEffectType(),
          };
        }),
      };
      if (layer.getName() === '') inspectedLayer.isBaseLayer = true;
      return inspectedLayer;
    }),
    childObjects,
    objectGroups: mapFor(0, objectGroups.count(), i => {
      const objectGroup = objectGroups.getAt(i);
      return {
        objectGroupName: objectGroup.getName(),
        objectNames: objectGroup.getAllObjectsNames().toJSArray(),
      };
    }),
    instances,
  };
  if (variant.getAssetStoreAssetId())
    inspectedVariant.assetStoreAssetId = variant.getAssetStoreAssetId();
  if (variant.getAssetStoreOriginalName())
    inspectedVariant.assetStoreOriginalName = variant.getAssetStoreOriginalName();
  return inspectedVariant;
};

/**
 * True when the generated metadata of the extension is registered in the
 * platform. When it is not (the extension was just created or changed), call
 * forms cannot be computed and the output says so.
 */
const isExtensionInPlatform = (
  platform: gdPlatform,
  extensionName: string
): boolean => {
  const platformExtensions = platform.getAllPlatformExtensions();
  for (let i = 0; i < platformExtensions.size(); i++) {
    if (platformExtensions.at(i).getName() === extensionName) return true;
  }
  return false;
};

