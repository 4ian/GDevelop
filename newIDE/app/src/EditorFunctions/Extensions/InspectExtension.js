export type CallFormContext = {|
  extensionName: string,
  owner: FunctionOwner,
  // `Ext::Obj` / `Ext::Beh` for object and behavior functions, null for free ones.
  ownerType: string | null,
|};

const getInstructionType = (
  context: CallFormContext,
  functionName: string
): string =>
  context.ownerType
    ? `${context.ownerType}::${functionName}`
    : `${context.extensionName}::${functionName}`;

// The value assigned/compared by an operator-based function, and the argument
// name used when a parameter has no declared name.
const DEFAULT_ARGUMENT_NAME_BY_TYPE: { [string]: string } = {
  expression: 'Value',
  number: 'Value',
  string: 'Value',
};

/**
 * The arguments of a call form. The GENERATED metadata drops the parameter
 * names, so they are read from the DECLARED parameters of the function with a
 * separate cursor: the two lists differ by the code-only parameters (a
 * `currentScene` first for free functions, the `eventsFunctionContext` last)
 * and by the operator + value pair inserted for operator-based functions.
 */
const renderCallFormArguments = (
  metadata: gdInstructionMetadata | gdExpressionMetadata,
  context: CallFormContext,
  declaredParameters: Array<SimplifiedParameter>,
  withImplicitArguments: boolean
): Array<string> => {
  const implicitCount = getImplicitParametersCount(context.owner);
  const args = [];
  let declaredIndex = implicitCount;
  let previousWasOperator = false;
  for (let index = 0; index < metadata.getParametersCount(); index++) {
    const parameterMetadata = metadata.getParameter(index);
    if (parameterMetadata.isCodeOnly()) continue;
    const type = parameterMetadata.getType();
    if (index < implicitCount) {
      if (withImplicitArguments) args.push(index === 0 ? 'Object' : 'Behavior');
    } else if (type === 'operator' || type === 'relationalOperator') {
      args.push(type === 'operator' ? '=' : '>');
      previousWasOperator = true;
    } else if (previousWasOperator) {
      args.push('Value');
      previousWasOperator = false;
    } else {
      const declaredParameter = declaredParameters[declaredIndex++];
      args.push(
        (declaredParameter && declaredParameter.name) ||
          DEFAULT_ARGUMENT_NAME_BY_TYPE[type] ||
          type
      );
    }
  }
  return args;
};

const renderInstructionCallForm = (
  instructionType: string,
  metadata: gdInstructionMetadata,
  context: CallFormContext,
  declaredParameters: Array<SimplifiedParameter>
): string =>
  `${
    metadata.isAsync() ? 'await ' : ''
  }${instructionType}(${renderCallFormArguments(
    metadata,
    context,
    declaredParameters,
    true
  ).join(', ')})`;

const renderExpressionCallForm = (
  functionName: string,
  metadata: gdExpressionMetadata,
  context: CallFormContext,
  declaredParameters: Array<SimplifiedParameter>
): string => {
  const prefix =
    context.owner === 'object'
      ? 'Object.'
      : context.owner === 'behavior'
      ? 'Object.Behavior::'
      : `${context.extensionName}::`;
  return `${prefix}${functionName}(${renderCallFormArguments(
    metadata,
    context,
    declaredParameters,
    false
  ).join(', ')})`;
};

const getInstructionCallForm = (
  platform: gdPlatform,
  context: CallFormContext,
  functionName: string,
  kind: 'action' | 'condition',
  declaredParameters: Array<SimplifiedParameter>
): string | null => {
  const instructionType = getInstructionType(context, functionName);
  const metadata =
    kind === 'action'
      ? gd.MetadataProvider.getActionMetadata(platform, instructionType)
      : gd.MetadataProvider.getConditionMetadata(platform, instructionType);
  if (gd.MetadataProvider.isBadInstructionMetadata(metadata)) return null;
  return renderInstructionCallForm(
    instructionType,
    metadata,
    context,
    declaredParameters
  );
};

// Expressions are looked up by their bare name on the object/behavior type, and
// by `Ext::Fn` for free functions - and in both the number and string tables.
const getExpressionCallForm = (
  platform: gdPlatform,
  context: CallFormContext,
  functionName: string,
  declaredParameters: Array<SimplifiedParameter>
): string | null => {
  const { owner, ownerType, extensionName } = context;
  const expressionName =
    owner === 'extension' ? `${extensionName}::${functionName}` : functionName;
  const candidates =
    owner === 'object' && ownerType
      ? [
          gd.MetadataProvider.getObjectExpressionMetadata(
            platform,
            ownerType,
            expressionName
          ),
          gd.MetadataProvider.getObjectStrExpressionMetadata(
            platform,
            ownerType,
            expressionName
          ),
        ]
      : owner === 'behavior' && ownerType
      ? [
          gd.MetadataProvider.getBehaviorExpressionMetadata(
            platform,
            ownerType,
            expressionName
          ),
          gd.MetadataProvider.getBehaviorStrExpressionMetadata(
            platform,
            ownerType,
            expressionName
          ),
        ]
      : [
          gd.MetadataProvider.getExpressionMetadata(platform, expressionName),
          gd.MetadataProvider.getStrExpressionMetadata(
            platform,
            expressionName
          ),
        ];
  for (const metadata of candidates) {
    if (!gd.MetadataProvider.isBadExpressionMetadata(metadata)) {
      return renderExpressionCallForm(
        functionName,
        metadata,
        context,
        declaredParameters
      );
    }
  }
  return null;
};

/**
 * The EventScript call form(s) of a function and the instruction type it was
 * read from. Both are empty for a lifecycle function and when the extension
 * has no generated metadata in the editor yet.
 */
export const getCallFormsAndInstructionType = (
  platform: gdPlatform,
  context: CallFormContext,
  simplifiedFunction: SimplifiedFunction,
  getterFunction: SimplifiedFunction | null
): {| callForms: Array<string>, instructionType: string | null |} => {
  const { functionName, functionType } = simplifiedFunction;
  if (simplifiedFunction.isLifecycle)
    return { callForms: [], instructionType: null };

  // An `ActionWithOperator` takes the parameters of its getter.
  const declaredParameters = getterFunction
    ? getterFunction.parameters
    : simplifiedFunction.parameters;
  const forms = [];
  let instructionType = null;

  const addInstructionForm = (kind: 'action' | 'condition') => {
    const form = getInstructionCallForm(
      platform,
      context,
      functionName,
      kind,
      declaredParameters
    );
    if (form) {
      forms.push(form);
      instructionType = getInstructionType(context, functionName);
    }
  };
  const addExpressionForm = () => {
    const form = getExpressionCallForm(
      platform,
      context,
      functionName,
      declaredParameters
    );
    if (form) {
      forms.push(form);
      if (!instructionType) {
        instructionType =
          context.owner === 'extension'
            ? `${context.extensionName}::${functionName}`
            : functionName;
      }
    }
  };

  if (functionType === 'Action' || functionType === 'ActionWithOperator') {
    addInstructionForm('action');
  } else if (functionType === 'Condition') {
    addInstructionForm('condition');
  } else if (functionType === 'Expression') {
    addExpressionForm();
  } else if (functionType === 'ExpressionAndCondition') {
    addExpressionForm();
    addInstructionForm('condition');
  }

  if (functionType === 'ActionWithOperator' && simplifiedFunction.getterName) {
    const getterForm = getExpressionCallForm(
      platform,
      context,
      simplifiedFunction.getterName,
      []
    );
    if (getterForm) forms.push(`read the value with ${getterForm}`);
  }

  return { callForms: forms, instructionType };
};

/** The same call forms, rendered as the single string the reads return. */
const getCallFormAndInstructionType = (
  platform: gdPlatform,
  context: CallFormContext,
  simplifiedFunction: SimplifiedFunction,
  getterFunction: SimplifiedFunction | null
): {| callForm?: string, instructionType?: string |} => {
  const { callForms, instructionType } = getCallFormsAndInstructionType(
    platform,
    context,
    simplifiedFunction,
    getterFunction
  );
  const result: {| callForm?: string, instructionType?: string |} = {};
  if (callForms.length > 0) result.callForm = callForms.join(' | ');
  if (instructionType) result.instructionType = instructionType;
  return result;
};

