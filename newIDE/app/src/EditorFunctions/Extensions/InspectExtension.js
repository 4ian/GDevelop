const getInspectedFunction = (
  platform: gdPlatform,
  context: CallFormContext,
  eventsFunctionsContainer: gdEventsFunctionsContainer,
  eventsFunction: gdEventsFunction,
  withOwner: boolean
): InspectedFunction => {
  const simplifiedFunction = getSimplifiedFunction(
    gd,
    eventsFunction,
    context.owner
  );
  const getterName = simplifiedFunction.getterName;
  const getterFunction =
    simplifiedFunction.functionType === 'ActionWithOperator' &&
    getterName &&
    eventsFunctionsContainer.hasEventsFunctionNamed(getterName)
      ? getSimplifiedFunction(
          gd,
          eventsFunctionsContainer.getEventsFunction(getterName),
          context.owner
        )
      : null;
  const inspectedFunction: InspectedFunction = {
    ...simplifiedFunction,
    ...getCallFormAndInstructionType(
      platform,
      context,
      simplifiedFunction,
      getterFunction
    ),
  };
  if (withOwner) inspectedFunction.owner = context.owner;
  if (!simplifiedFunction.isLifecycle && !inspectedFunction.callForm) {
    inspectedFunction.callFormUnavailableReason = CALL_FORM_UNAVAILABLE_REASON;
  }
  if (simplifiedFunction.isLifecycle) {
    const lifecycleDescription =
      LIFECYCLE_DESCRIPTIONS[context.owner][simplifiedFunction.functionName];
    if (lifecycleDescription)
      inspectedFunction.lifecycleDescription = lifecycleDescription;
  }
  return inspectedFunction;
};

