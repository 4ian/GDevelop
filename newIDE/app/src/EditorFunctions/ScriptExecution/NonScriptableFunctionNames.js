// @flow

/**
 * Editor functions NEVER exposed inside a script:
 * - `run_script` itself (no recursion),
 * - `initialize_project` (only when no project is open),
 * - the server-side tools (docs/search/sub-agents/plan/report/events): they are
 *   resolved in the Lambda and stay plain tool calls next to `run_script`; their
 *   client-side entries are stubs that would just fail if called from a script.
 * Everything else client-side (mutations, inspections, `read_events_source`) is
 * scriptable.
 *
 * In its own module so `ExposedFunctions.js` and `ScriptRunner.js` do not have
 * to import each other.
 */
export const NON_SCRIPTABLE_FUNCTION_NAMES: Set<string> = new Set([
  'run_script',
  'initialize_project',
  // Server-side tools (resolved in the Lambda):
  'read_full_docs',
  'search_docs',
  'search_object_asset_store',
  'search_resource_store',
  'create_or_update_plan',
  'report_fulfilment_problem',
  'run_edit_agent',
  'run_explorer_agent',
  'read_game_project_json',
  'get_game_starter_summary',
  // Events are generated by the orchestrator (`generate_events`), never inside
  // an edit/explorer script (v1 scope).
  'generate_events',
  'add_scene_events',
  // Gameplay tests launch a real game preview (seconds long): they are plain
  // tool calls (`run_tests` for the orchestrator, `run_gameplay_test` for the
  // tester agent), never called from inside a script.
  'run_tests',
  'run_gameplay_test',
]);
