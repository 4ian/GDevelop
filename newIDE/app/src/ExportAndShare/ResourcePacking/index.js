// @flow
import {
  planResourcePacks,
  type ResourcePackPlan,
} from './ResourcePackPlanner';

export { planResourcePacks };
export type { ResourcePackPlan };

/**
 * Resource kinds that are never packed.
 *
 * `PIXI.Assets`, used to load Spine skeletons and atlases, picks its loader
 * from the extension of the URL - and a `blob:` URL has none. These are only a
 * couple of files per Spine object, so leaving them out of the packs does not
 * threaten the file count. Their pages are plain images and are still packed.
 */
export const RESOURCE_KINDS_NEVER_PACKED = ['spine', 'atlas'];

const PROJECT_DATA_PREFIX = 'gdjs.projectData = ';
const RUNTIME_GAME_OPTIONS_PREFIX = 'gdjs.runtimeGameOptions = ';

/**
 * Read back the project data that the exporter wrote in `data.js`.
 *
 * The file is generated by `ExporterHelper::ExportProjectData` and always has
 * the shape:
 *
 *   gdjs.projectData = {...};
 *   gdjs.runtimeGameOptions = {...};
 *
 * This is the authoritative list of the resources of the exported game. The
 * files present in the export folder cannot be used instead: the engine files
 * are copied the same way as the resources.
 */
export const readProjectDataFromDataJs = (dataJsContent: string): Object => {
  const projectDataStart = dataJsContent.indexOf(PROJECT_DATA_PREFIX);
  const runtimeGameOptionsStart = dataJsContent.lastIndexOf(
    RUNTIME_GAME_OPTIONS_PREFIX
  );
  if (projectDataStart === -1 || runtimeGameOptionsStart === -1) {
    throw new Error(
      'Could not read the project data of the exported game: "data.js" does not have the expected content.'
    );
  }

  const json = dataJsContent
    .slice(
      projectDataStart + PROJECT_DATA_PREFIX.length,
      runtimeGameOptionsStart
    )
    .trim()
    // Remove the trailing ";" of the assignment.
    .replace(/;$/, '');

  return JSON.parse(json);
};

export type ResourcePacksManifest = {|
  version: number,
  packs: Array<string>,
  files: { [filePath: string]: number },
  /**
   * Packs to download before the first scene starts, even though no loading
   * task refers to their files. See `PlannedPack.isLoadedAtStartup`.
   */
  startupPacks: Array<number>,
|};

/**
 * Build the manifest read by the game engine.
 *
 * `packedFilePaths` holds the files that were really written: a resource the
 * export does not contain is skipped, and must not be announced as being in a
 * pack. Pack names keep their index even when a pack ended up empty, so that
 * the indexes of the manifest stay the ones the plan computed.
 */
export const buildResourcePacksManifest = (
  plan: ResourcePackPlan,
  packedFilePaths: Set<string>
): ResourcePacksManifest => {
  const files: { [filePath: string]: number } = {};
  Object.keys(plan.fileToPackIndex).forEach(filePath => {
    if (!packedFilePaths.has(filePath)) return;
    files[filePath] = plan.fileToPackIndex[filePath];
  });

  const startupPacks = [];
  plan.packs.forEach((pack, packIndex) => {
    // A pack whose files were all missing is never written, so asking the game
    // to download it would only produce a 404.
    const wasWritten = pack.filePaths.some(filePath =>
      packedFilePaths.has(filePath)
    );
    if (pack.isLoadedAtStartup && wasWritten) startupPacks.push(packIndex);
  });

  return {
    version: 1,
    packs: plan.packs.map(pack => pack.name),
    files,
    startupPacks,
  };
};

/**
 * Declare the packs to the game engine, which reads `gdjs.resourcePacks` when
 * it sets up its resource loader (see `GDJS/Runtime/ResourcePackManager.ts`).
 *
 * This is appended to `data.js` rather than passed through
 * `gdjs.runtimeGameOptions`, because a full export instantiates the game with
 * an empty options object (see the `GDJS_ADDITIONAL_SPEC` placeholder in
 * `GDJS/Runtime/index.html`).
 */
export const appendResourcePacksManifestToDataJs = (
  dataJsContent: string,
  manifest: ResourcePacksManifest
): string =>
  dataJsContent + 'gdjs.resourcePacks = ' + JSON.stringify(manifest) + ';\n';
